//! Build-time link verification: resolves every catalog item, downloads non-winget installers
//! (HEAD only above --max-mb), checks hashes/signatures, sniffs the installer type, and writes catalog-report.md.
//! Usage: cargo run --bin verify-catalog -- [--max-mb 400] [--out ../catalog-report.md]

use setup_hub_lib::{catalog, download, gpu, sig, util};
use std::fmt::Write as _;
use std::sync::atomic::AtomicBool;

fn sniff(path: &std::path::Path) -> &'static str {
    let ext = path.extension().and_then(|e| e.to_str()).unwrap_or("").to_ascii_lowercase();
    if ext == "msi" {
        return "MSI";
    }
    if ext == "zip" {
        return "ZIP";
    }
    if ext.starts_with("msix") || ext.starts_with("appx") {
        return "MSIX";
    }
    let data = std::fs::read(path).unwrap_or_default();
    let has = |s: &[u8]| data.windows(s.len()).any(|w| w == s);
    if has(b"Inno Setup") {
        "Inno Setup"
    } else if has(b"Nullsoft") || has(b"NSIS Error") {
        "NSIS"
    } else if has(b"Squirrel") || has(b"SquirrelSetup") {
        "Squirrel"
    } else if has(b".wixburn") {
        "WiX/Burn"
    } else if has(b"InstallShield") {
        "InstallShield"
    } else {
        "EXE (unknown)"
    }
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let args: Vec<String> = std::env::args().collect();
    let arg = |k: &str| args.iter().position(|a| a == k).and_then(|i| args.get(i + 1)).cloned();
    let max_mb: u64 = arg("--max-mb").and_then(|s| s.parse().ok()).unwrap_or(400);
    let out = arg("--out").unwrap_or_else(|| "../catalog-report.md".into());
    let token = std::env::var("GITHUB_TOKEN").ok();
    let cat = catalog::parse(catalog::EMBEDDED)?;
    let cancel = AtomicBool::new(false);
    let dir = std::env::temp_dir().join("SetupHub").join("verify");

    let mut md = String::new();
    writeln!(md, "# Catalog verification report\n")?;
    writeln!(md, "Generated by `cargo run --bin verify-catalog` on {}.\n", chrono_now())?;
    writeln!(md, "| # | App | Route | Resolved URL | Version | Type | Signature / hash | Silent args | Result |")?;
    writeln!(md, "|---|-----|-------|--------------|---------|------|------------------|-------------|--------|")?;

    let only: Vec<String> = arg("--only").map(|s| s.split(',').map(str::to_string).collect()).unwrap_or_default();
    for (n, it) in cat.items.iter().enumerate() {
        if !only.is_empty() && !only.contains(&it.id) {
            continue;
        }
        eprintln!("== {}", it.id);
        let mut route = Vec::new();
        let mut version = String::new();
        let (mut url, mut kind, mut signature, mut result) = (String::new(), String::new(), String::new(), "PASS".to_string());

        if let Some(w) = &it.winget_id {
            let (code, o) = util::run("winget.exe", &["show", "--id", w, "-e", "--source", "winget", "--accept-source-agreements", "--disable-interactivity"]).await?;
            if code == 0 {
                version = o.lines().find_map(|l| l.trim().strip_prefix("Version:")).unwrap_or("").trim().to_string();
                let iu = o.lines().find_map(|l| l.trim().strip_prefix("Installer Url:")).unwrap_or("").trim().to_string();
                let it = o.lines().find_map(|l| l.trim().strip_prefix("Installer Type:")).unwrap_or("").trim().to_string();
                route.push(format!("winget `{w}`"));
                url = iu;
                kind = it;
                signature = "winget verifies the manifest SHA-256".into();
            } else {
                route.push(format!("winget `{w}` **NOT FOUND**"));
                result = "FAIL".into();
            }
        }

        if !matches!(it.source, catalog::Source::Winget) {
            route.push(match &it.source {
                catalog::Source::Direct { .. } => "direct".into(),
                catalog::Source::Scrape { .. } => "vendor page".into(),
                catalog::Source::GithubRelease { repo, .. } => format!("GitHub `{repo}`"),
                catalog::Source::Winget => unreachable!(),
            });
            match catalog::resolve(it, token.as_deref()).await {
                Err(e) => {
                    result = format!("FAIL: {e:#}");
                }
                Ok(r) => {
                    if it.winget_id.is_none() {
                        version = r.version.clone().unwrap_or_default();
                    }
                    let fallback_url = r.url.clone();
                    let client = util::http(it.allowed_hosts.clone());
                    let head = client.head(&r.url).send().await;
                    let len = head.as_ref().ok().and_then(|h| h.content_length()).unwrap_or(0);
                    let status = head.as_ref().map(|h| h.status().as_u16()).unwrap_or(0);
                    let mut sigtxt;
                    if !(200..400).contains(&status) && status != 405 {
                        sigtxt = format!("HTTP {status}");
                        result = "FAIL".into();
                    } else if len > max_mb * 1_000_000 {
                        sigtxt = format!("HEAD ok ({} MB) — too large to download here, verified at runtime", len / 1_000_000);
                        if kind.is_empty() {
                            kind = "ZIP".into();
                        }
                    } else {
                        let d = dir.join(&it.id);
                        let _ = std::fs::remove_dir_all(&d);
                        match download::fetch(&client, &r.url, &d, &cancel, &|_, _| {}).await {
                            Err(e) => {
                                sigtxt = format!("download failed: {e:#}");
                                result = "FAIL".into();
                            }
                            Ok(f) => {
                                let k = sniff(&f);
                                if kind.is_empty() || it.winget_id.is_some() {
                                    kind = if it.winget_id.is_some() && !kind.is_empty() { format!("{kind} / fallback: {k}") } else { k.into() };
                                }
                                let mut target = f.clone();
                                if k == "ZIP" {
                                    let x = d.join("x");
                                    let files = setup_hub_lib::installer::unzip(&f, &x)?;
                                    let z = it.zip.clone().unwrap_or_default();
                                    let re = match (&z.shortcut, &z.run) {
                                        (Some(exe), _) => format!("(?i)^{}$", regex::escape(exe)),
                                        (None, Some(r)) => r.clone(),
                                        _ => r"(?i)\.exe$".into(),
                                    };
                                    let re = regex::Regex::new(&re)?;
                                    if let Some(t) = files.iter().find(|p| re.is_match(&p.file_name().unwrap_or_default().to_string_lossy())) {
                                        target = t.clone();
                                    }
                                }
                                let s = sig::authenticode(&target).await?;
                                sigtxt = format!("{} {}", s.status, s.publisher.clone().unwrap_or_default());
                                match sig::verify(&target, if k == "ZIP" { None } else { r.sha256.as_deref() }, it.publisher.as_deref()).await {
                                    Ok(v) => sigtxt = v,
                                    Err(e) => {
                                        sigtxt = format!("{sigtxt} — {e:#}");
                                        result = "FAIL".into();
                                    }
                                }
                                if r.sha256.is_some() && k != "ZIP" {
                                    sigtxt.push_str(" (GitHub digest)");
                                }
                            }
                        }
                        let _ = std::fs::remove_dir_all(&d);
                    }
                    if !signature.is_empty() {
                        signature = format!("{signature}; fallback: {sigtxt}");
                        url = format!("{url}<br>fallback: {fallback_url}");
                    } else {
                        signature = sigtxt;
                        url = fallback_url;
                    }
                }
            }
        }
        if it.interactive && result == "PASS" {
            result = "PASS (needs interaction)".into();
        }
        let args = if it.winget_id.is_some() && it.silent_args.is_empty() { "winget --silent".to_string() } else { it.silent_args.join(" ") };
        writeln!(md, "| {} | {} | {} | {} | {} | {} | {} | `{}` | {} |", n + 1, it.name, route.join(" → "), url, version, kind, signature, args, result)?;
    }

    // NVIDIA driver lookup for this machine's GPU (or the user's RTX 4080 SUPER).
    writeln!(md, "\n## NVIDIA Game Ready driver\n")?;
    let gpus = gpu::detect().await.unwrap_or_default();
    let name = gpus.iter().find(|g| g.vendor == gpu::Vendor::Nvidia).map(|g| g.name.clone()).unwrap_or("NVIDIA GeForce RTX 4080 SUPER".into());
    match gpu::latest_nvidia(&name).await {
        Ok(d) => writeln!(md, "- GPU `{name}` → **{}** ({}), {} — {}", d.version, d.release_date, d.size, d.url)?,
        Err(e) => writeln!(md, "- GPU `{name}` → lookup FAILED: {e:#}")?,
    }
    match gpu::nvidia_app_url().await {
        Ok(u) => writeln!(md, "- NVIDIA App fallback: {u}")?,
        Err(e) => writeln!(md, "- NVIDIA App fallback: FAILED {e:#}")?,
    }
    std::fs::write(&out, md)?;
    eprintln!("wrote {out}");
    Ok(())
}

fn chrono_now() -> String {
    let s = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_secs();
    let days = s / 86400;
    // civil-from-days (Howard Hinnant), good for a report stamp
    let z = days as i64 + 719468;
    let era = z.div_euclid(146097);
    let doe = z - era * 146097;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + if m <= 2 { 1 } else { 0 };
    format!("{y:04}-{m:02}-{d:02}")
}
